#!/usr/bin/env bash
# Regenerate fonts/fonts-manifest.local.js from the font files in fonts/ (macOS / Linux).
# Windows: double-click update-fonts-manifest.cmd instead (same behaviour).
#
# The committed fonts/fonts-manifest.js (fonts shipped with the repo) is only read, never written.
# This script lists every OTHER font file in fonts/ in the git-ignored fonts-manifest.local.js, which
# index.html loads in addition. Keeps the display name and order of fonts already listed, drops entries
# whose file is gone, and appends new files (named after the filename) at the end.
# The first local entry is the font selected when the page loads.
#
# Usage (from the project folder): ./scripts/update-fonts-manifest.sh   (or: bash scripts/update-fonts-manifest.sh)
set -eu

FONTS_DIR="$(cd "$(dirname "$0")/../fonts" && pwd)"
SHIPPED="$FONTS_DIR/fonts-manifest.js"        # committed, read only
MANIFEST="$FONTS_DIR/fonts-manifest.local.js"  # generated, git-ignored
TAB=$'\t'

# Font files named in the committed manifest: they are loaded from there, so they are skipped here.
shipped=""
if [ -f "$SHIPPED" ]; then
  shipped=$(sed -n 's/^.*{ *name: *"\(.*\)" *, *file: *"\(.*\)" *}.*$/\2/p' "$SHIPPED" | sed 's/\\\(.\)/\1/g')
fi

# Other font files present, sorted case-insensitively, one per line.
files=$(cd "$FONTS_DIR" && for f in *; do
  [ -f "$f" ] || continue
  case "$(printf '%s' "${f##*.}" | tr '[:upper:]' '[:lower:]')" in
    (otf|ttf|woff|woff2) grep -qxF -- "$f" <<< "$shipped" || printf '%s\n' "$f" ;;
  esac
done | sort -f)

# Existing manifest entries as "name<TAB>file" lines.
existing=""
if [ -f "$MANIFEST" ]; then
  existing=$(sed -n 's/^.*{ *name: *"\(.*\)" *, *file: *"\(.*\)" *}.*$/\1'"$TAB"'\2/p' "$MANIFEST" \
    | sed 's/\\\(.\)/\1/g')
fi

entries=""
while IFS="$TAB" read -r name file; do
  [ -n "$file" ] || continue
  if grep -qxF -- "$file" <<< "$files"; then entries+="$name$TAB$file"$'\n'; fi
done <<< "$existing"
while IFS= read -r file; do
  [ -n "$file" ] || continue
  if ! cut -f2 <<< "$entries" | grep -qxF -- "$file"; then entries+="${file%.*}$TAB$file"$'\n'; fi
done <<< "$files"
entries=${entries%$'\n'}

esc() { printf '%s' "$1" | sed 's/[\\"]/\\&/g'; }

{
  echo '// Generated by update-fonts-manifest.sh / .cmd - rerun it after adding/removing font files.'
  echo '// Local fonts only (this file is git-ignored). Fonts shipped with the repo are in fonts-manifest.js.'
  echo '// You can edit display names or reorder lines by hand; the script keeps both.'
  echo '// The first font listed here is selected when the page loads.'
  if [ -z "$entries" ]; then
    echo 'window.LOCAL_FONTS_EXTRA = [];'
  else
    echo 'window.LOCAL_FONTS_EXTRA = ['
    count=$(grep -c '' <<< "$entries")
    i=0
    while IFS="$TAB" read -r name file; do
      i=$((i + 1))
      sep=","; [ "$i" -eq "$count" ] && sep=""
      printf '  { name: "%s", file: "%s" }%s\n' "$(esc "$name")" "$(esc "$file")" "$sep"
    done <<< "$entries"
    echo '];'
  fi
} > "$MANIFEST"

echo "fonts/fonts-manifest.local.js: $(if [ -z "$entries" ]; then echo 0; else grep -c '' <<< "$entries"; fi) font(s)"
[ -z "$entries" ] || while IFS="$TAB" read -r name file; do echo "  $name  <-  $file"; done <<< "$entries"
